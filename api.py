"""FastAPI service exposing CRUD operations for country records."""

import sqlite3
from pathlib import Path as FilePath

from fastapi import FastAPI, HTTPException, Path, Response, status
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, ConfigDict, Field

from database import CountryDatabaseManager


class CountryPayload(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True)

    country_name: str = Field(min_length=1)
    capital: str = Field(min_length=1)
    population: int = Field(ge=0)
    area_sq_km: float = Field(ge=0)


class CountryUpdatePayload(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True)

    capital: str = Field(min_length=1)
    population: int = Field(ge=0)
    area_sq_km: float = Field(ge=0)


app = FastAPI(
    title="Country Data API",
    description="CRUD API for the country data capstone project.",
    version="1.0.0",
)
database = CountryDatabaseManager()
PROJECT_DIR = FilePath(__file__).resolve().parent
STATIC_DIR = PROJECT_DIR / "static"
app.mount("/static", StaticFiles(directory=STATIC_DIR), name="static")


@app.get("/", include_in_schema=False)
def dashboard() -> FileResponse:
    """Serve the project dashboard at the API root."""
    return FileResponse(STATIC_DIR / "index.html")


@app.get("/population_vs_area.png", include_in_schema=False)
def population_area_chart() -> FileResponse:
    """Serve the chart generated by ``visualize.py``."""
    chart_path = PROJECT_DIR / "population_vs_area.png"
    if not chart_path.exists():
        raise HTTPException(status_code=404, detail="Run visualize.py to create the chart")
    return FileResponse(chart_path)


@app.get("/countries", response_model=list[CountryPayload])
def list_countries() -> list[dict]:
    return database.get_all_countries()


@app.get("/countries/{country_name}", response_model=CountryPayload)
def get_country(country_name: str = Path(min_length=1)) -> dict:
    country = database.get_country(country_name)
    if country is None:
        raise HTTPException(status_code=404, detail="Country not found")
    return country


@app.post("/countries", response_model=CountryPayload, status_code=status.HTTP_201_CREATED)
def create_country(payload: CountryPayload) -> dict:
    country = payload.model_dump()
    try:
        return database.create_country(country)
    except sqlite3.IntegrityError as error:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="A country with that name already exists",
        ) from error


@app.put("/countries/{country_name}", response_model=CountryPayload)
def update_country(
    payload: CountryUpdatePayload,
    country_name: str = Path(min_length=1),
) -> dict:
    country = database.update_country(country_name, payload.model_dump())
    if country is None:
        raise HTTPException(status_code=404, detail="Country not found")
    return country


@app.delete("/countries/{country_name}", status_code=status.HTTP_204_NO_CONTENT)
def delete_country(country_name: str = Path(min_length=1)) -> Response:
    if not database.delete_country(country_name):
        raise HTTPException(status_code=404, detail="Country not found")
    return Response(status_code=status.HTTP_204_NO_CONTENT)
